global fibonacci
    section .text

fibonacci:
    ;Створення стекового кадру (стек-фрейму)
    push rbp
    mov  rbp, rsp
    ;Фіксуємо базовий вказівник rbp для поточної глибини рекурсії, 
    ;щоб адресація локальних даних залишалася стабільною незалежно від зміщення вказівника rsp.

    ;Збереження регістрового контексту у стек
    push rbx
    push r12
    ;Функція зобов'язана повернути їх викликачу в незмінному вигляді. 
    ;Ми зберігаємо їх у стек перед використанням, щоб не пошкодити дані зовнішньої програми на C.

    ;Захист вхідного аргументу
    mov ebx, edi
    ;Вхідне число n надходить у регістрі edi. Оскільки для обчислення другого доданка 
    ;fib(n-2) нам знадобиться початкове n, а перший рекурсивний виклик затре регістр edi 
    ;значенням (n-1), ми копіюємо n у збережений регістр ebx, де воно гарантовано вціліє.

    ;Базовий випадок 1: n == 0
    cmp ebx, 0
    jne .check_one
    xor eax, eax             ; Очищення eax (результат = 0)
    jmp .epilogue
    ;Якщо досягнуто n = 0, повертаємо 0 через регістр eax.

    ;Базовий випадок 2: n == 1
.check_one:
    cmp ebx, 1
    jne .recursive_step
    mov eax, 1               ; Результат = 1
    jmp .epilogue
    ;Якщо n = 1, повертаємо 1 через eax без подальшого заглиблення в дерево викликів.

    ;Рекурсивний крок: fibonacci(n - 1) + fibonacci(n - 2)
.recursive_step:
    ;Обчислення fibonacci(n - 1)
    lea edi, [rbx - 1]       ;Формуємо аргумент (n - 1) для першого виклику
    call fibonacci           ;Виклик функції. Адреса повернення автоматично кладеться процесором у стек

    ;Збереження проміжного результату
    mov r12, rax
    ;Перший виклик повернув fib(n-1) у регістр rax. Оскільки наступний виклик 
    ;функції перезапише rax результатом другого виклику, ми ховаємо першу відповідь у r12.

    ;Обчислення fibonacci(n - 2)
    lea edi, [rbx - 2]       ; Формуємо аргумент (n - 2) для другого виклику, використовуючи збережене в rbx число n
    call fibonacci           ; Результат fib(n-2) опиняється в rax

    ; Об'єднання результатів
    add rax, r12
    ;Додаємо збережений у r12 результат fib(n-1) до щойно отриманого в rax результату fib(n-2).
    ;Загальна сума залишається в rax як підсумкове значення виклику.

    ;Відновлення стану машини перед поверненням
.epilogue:
    pop r12
    pop rbx
    ;Відновлюємо початкові значення регістрів викликача зі стеку у зворотному порядку 
    ;для суворого дотримання контракту ABI.

    mov rsp, rbp
    pop rbp
    ;Демонтуємо стек-фрейм поточної ітерації, повертаючи вказівник вершини стека rsp на місце.

    ret
    ;Процесор зчитує зі стека збережену команду адреси повернення і передає керування 
    ;або на попередній рівень рекурсії, або у функцію main.